"""
Single-link URDF: one `<collision><box>` per geometry box, the STL union as the visual, analytic inertia.
"""

import xml.etree.ElementTree as ET
from pathlib import Path

import numpy as np

from .geometry import Box


def mass_properties(
    boxes: tuple[Box, ...] | list[Box], mass: float
) -> tuple[np.ndarray, np.ndarray]:
    """Centre of mass and inertia tensor about it, for `mass` spread uniformly over the (disjoint) boxes."""
    volumes = np.array([b.volume for b in boxes])
    masses = mass * volumes / volumes.sum()
    centres = np.array([b.center for b in boxes])
    com = (masses[:, None] * centres).sum(axis=0) / mass
    inertia = np.zeros((3, 3))
    for m, b, c in zip(masses, boxes, centres, strict=True):
        sx, sy, sz = b.size
        own = m / 12 * np.diag([sy**2 + sz**2, sx**2 + sz**2, sx**2 + sy**2])
        d = c - com
        # parallel axis theorem
        inertia += own + m * (d @ d * np.eye(3) - np.outer(d, d))
    return com, inertia


def write_urdf(
    path: str | Path,
    name: str,
    boxes: tuple[Box, ...] | list[Box],
    mass: float,
    visual_mesh: str,
    rgba: tuple[float, float, float, float],
) -> None:
    """`visual_mesh` is relative to the URDF file."""
    robot = ET.Element("robot", name=name)
    link = ET.SubElement(robot, "link", name=f"{name}_link")

    visual = ET.SubElement(link, "visual")
    ET.SubElement(ET.SubElement(visual, "geometry"), "mesh", filename=visual_mesh)
    material = ET.SubElement(visual, "material", name=f"{name}_color")
    ET.SubElement(material, "color", rgba=_fmt(rgba))

    for box in boxes:
        collision = ET.SubElement(link, "collision")
        ET.SubElement(collision, "origin", xyz=_fmt(box.center), rpy="0 0 0")
        ET.SubElement(ET.SubElement(collision, "geometry"), "box", size=_fmt(box.size))

    com, inertia = mass_properties(boxes, mass)
    inertial = ET.SubElement(link, "inertial")
    ET.SubElement(inertial, "origin", xyz=_fmt(com), rpy="0 0 0")
    ET.SubElement(inertial, "mass", value=_fmt([mass]))
    ET.SubElement(
        inertial,
        "inertia",
        ixx=_fmt([inertia[0, 0]]),
        ixy=_fmt([inertia[0, 1]]),
        ixz=_fmt([inertia[0, 2]]),
        iyy=_fmt([inertia[1, 1]]),
        iyz=_fmt([inertia[1, 2]]),
        izz=_fmt([inertia[2, 2]]),
    )

    ET.indent(robot)
    comment = (
        "Generated by aegis_gym.aux.pih_assets, do not edit: change nominal.yaml (or the overrides) and run "
        "python3 -m scripts.peg_in_hole.generate_assets."
    )
    xml = ET.tostring(robot, encoding="unicode")
    Path(path).write_text(f'<?xml version="1.0"?>\n<!-- {comment} -->\n{xml}\n')


def _fmt(values) -> str:
    # 12 significant digits keep sub-micrometre clearances exact through the round trip
    return " ".join(f"{float(v):.12g}" for v in values)
